// Writes apps/aihtml/priv/css/extra/index.css: one @import per component
// stylesheet in extra/ (aihtml's own additions, one file per component or
// shared topic), in name order. components.css imports the index, so adding
// or removing an extra stylesheet needs no hand edit. Run by `npm run css`.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "apps/aihtml/priv/css/extra");
const files = readdirSync(dir).filter((f) => f.endsWith(".css") && f !== "index.css").sort();
writeFileSync(join(dir, "index.css"),
  "/* Generated by scripts/gen-css-index.mjs; do not edit. */\n" +
  files.map((f) => `@import "./${f}";\n`).join(""));
console.log(`extra/index.css: ${files.length} stylesheets`);

// Generates apps/aihtml/src/aihtml_lib_markdown_data.erl: the tables
// aihtml_lib_markdown needs to parse Markdown exactly like markdown-it,
// taken from the very packages markdown-it uses (node_modules):
//
//   entity(Name)     the HTML5 named character references markdown-it
//                    decodes (`entities' decodeHTMLStrict: `&name;' only)
//   legacy()         the names decodeHTML also decodes without the ";"
//                    (markdown-it's unescapeAll, in link destinations,
//                    titles and fence info strings)
//   punct_ranges()   Unicode punctuation and symbols (uc.micro P and S),
//                    markdown-it's isPunctChar, as sorted code point ranges
//
// Run it again when markdown-it (or entities / uc.micro) is upgraded:
//   node scripts/gen-markdown-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import * as ucmicro from "uc.micro";

const require = createRequire(import.meta.url);
const ent = require("entities/lib/decode.js");
const root = fileURLToPath(new URL("..", import.meta.url));

// Walk the decode trie for every name ending in ";" that decodeHTMLStrict
// turns into something else.
const tree = ent.htmlDecodeTree;
const chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789;";
const names = [];
const legacy = [];
(function walk(nodeIdx, prefix) {
  for (const c of chars) {
    const node = tree[nodeIdx];
    const valueLength = (node & ent.BinTrieFlags.VALUE_LENGTH) >> 14;
    const idx = ent.determineBranch(tree, node, nodeIdx + Math.max(1, valueLength), c.charCodeAt(0));
    if (idx < 0) { continue; }
    const name = prefix + c;
    if (c === ";") { names.push(name.slice(0, -1)); continue; }
    if ((tree[idx] & ent.BinTrieFlags.VALUE_LENGTH) >> 14) { legacy.push(name); }
    walk(idx, name);
  }
})(0, "");
const entities = [];
for (const n of names.sort()) {
  const s = "&" + n + ";";
  const d = ent.decodeHTMLStrict(s);
  if (d !== s && /^[a-z][a-z0-9]{1,31}$/i.test(n)) { entities.push([n, d]); }
}

// Punctuation and symbol code points as ranges.
const ranges = [];
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) { continue; }
  const s = String.fromCodePoint(c);
  if (ucmicro.P.test(s) || ucmicro.S.test(s)) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] === c - 1) { last[1] = c; } else { ranges.push([c, c]); }
  }
}

const bin = (s) => "<<" + [...Buffer.from(s, "utf8")].join(",") + ">>";
const out = `%%% Generated by scripts/gen-markdown-data.mjs from markdown-it's own
%%% dependencies (entities ${JSON.parse(readFileSync(root + "node_modules/entities/package.json", "utf8")).version}, uc.micro); do not edit.
%%% @private
-module(aihtml_lib_markdown_data).

-export([entity/1, legacy/0, punct_ranges/0]).

%% The text of an HTML5 named character reference (the name without & and ;).
-spec entity(binary()) -> binary() | undefined.
entity(Name) -> maps:get(Name, ?MODULE_STRING_ENTITIES, undefined).

%% The names of legacy references, decoded even without the ";".
-spec legacy() -> [binary()].
legacy() ->
    [${legacy.sort().map((n) => `<<"${n}">>`).join(", ")}].

%% Unicode punctuation and symbol code points: sorted, disjoint {First, Last}.
-spec punct_ranges() -> tuple().
punct_ranges() ->
    {${ranges.map(([a, b]) => `{${a},${b}}`).join(",\n     ")}}.
`.replace("?MODULE_STRING_ENTITIES",
          "#{" + entities.map(([n, d]) => `<<"${n}">> => ${bin(d)}`).join(",\n      ") + "}");
writeFileSync(root + "apps/aihtml/src/aihtml_lib_markdown_data.erl", out);
for (const n of legacy) {
  if (ent.decodeHTML("&" + n) !== ent.decodeHTMLStrict("&" + n + ";")) { throw new Error("legacy " + n); }
}
console.log(`${entities.length} entities, ${legacy.length} legacy, ${ranges.length} punctuation ranges`);
